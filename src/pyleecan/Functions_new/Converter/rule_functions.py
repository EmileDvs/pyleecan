DEPRECATED_RULE_FUNCTIONS = {
    "slotW23_H1": "slotw23_h1",
}
"""{rule name: module name} of the deprecated rule modules (loaded on
request, they warn)"""


def rule_function_module(fct_name):
    """Module of the functions of a complex rule

    Parameters
    ----------
    fct_name : str
        Name of the rule functions (RuleComplex.fct_name)

    Returns
    -------
    module : module
        Module with the other_to_P and P_to_other functions
    """
    if fct_name in RULE_FUNCTIONS:
        return RULE_FUNCTIONS[fct_name]
    if fct_name in DEPRECATED_RULE_FUNCTIONS:
        return import_module(
            f".MotorCAD.{DEPRECATED_RULE_FUNCTIONS[fct_name]}", __package__
        )
    raise KeyError(f"Unknown complex rule functions: {fct_name!r}")
